import axios from 'axios';

const API_BASE_URL = import.meta.env.VITE_API_BASE_URL || 'http://localhost:8000/api/v1';

export const api = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json',
  },
  withCredentials: true, // For HTTP-Only refresh token cookies
});

// Attach JWT Bearer Access Token to every outgoing request
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('projectflow_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Global response interceptor to handle 401 Unauthorized
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response?.status === 401) {
      // Clear expired credentials
      localStorage.removeItem('projectflow_token');
      localStorage.removeItem('projectflow_user');
    }
    return Promise.reject(error);
  }
);

export default api;
